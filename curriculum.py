def get_weight_for_subject(subject_name: str, target_major: str) -> float:
    if not target_major:
        return 1.0
    for major_key, weight_map in TARGET_MAJOR_WEIGHTS.items():
        if major_key in target_major:
            for subj_key, w in weight_map.items():
                if subj_key in subject_name:
                    return w
    return 1.0


def build_weighted_rotation(weighted_subjects):
    """یک چرخه‌ی «وزن‌دار» از دروس می‌سازد: دروسی که برای رشته هدف دانشگاهی کاربر
    وزن (اهمیت) بیشتری دارند، به‌طور طبیعی دفعات بیشتری در چرخه‌ی روزانه/هفتگی
    برنامه تکرار می‌شوند (نه فقط اول لیست قرار می‌گیرند). این باعث می‌شه برنامه
    دقیق‌تر با اهداف دانش‌آموز هماهنگ باشه.
    ورودی: لیستی از دیکشنری‌های {"name", "topics", "weight", ...}
    خروجی: همان آیتم‌ها، تکرارشده متناسب با وزن و درهم‌تنیده (interleaved)."""
    if not weighted_subjects:
        return []

    buckets = []
    for s in weighted_subjects:
        weight = s.get("weight") or 1.0
        repeat = max(1, round(weight * 2))
        buckets.append([s] * repeat)

    interleaved = []
    while any(buckets):
        for b in buckets:
            if b:
                interleaved.append(b.pop(0))
    return interleaved
